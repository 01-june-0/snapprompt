const catalogs: Record<Lang, Record<string, string>> = { ko, en, ja, zh };

/** Active resolved locale. Components reading `t()` re-render when this changes. */
export const locale = signal<Lang>('ko');

export function resolveLang(pref: LanguagePref): Lang {
  if (pref === 'ko' || pref === 'en' || pref === 'ja' || pref === 'zh') return pref;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('ko')) return 'ko';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('zh')) return 'zh';
  return 'en';
}

/** BCP-47 locale for Intl/Date formatting per active language. */
export function dateLocale(): string {
  return { ko: 'ko-KR', en: 'en-US', ja: 'ja-JP', zh: 'zh-CN' }[locale.value];
}

export function setLocale(pref: LanguagePref): void {
  locale.value = resolveLang(pref);
}

/** Translate. `{0}`, `{1}`… are replaced by `params`. */
export function t(key: string, params?: (string | number)[]): string {
  const lang = locale.value;
  let s = catalogs[lang][key] ?? catalogs.en[key] ?? catalogs.ko[key] ?? key;
  if (params) {
    params.forEach((p, i) => {
      s = s.split(`{${i}}`).join(String(p));
    });
  }
  return s;
}
