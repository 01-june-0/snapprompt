const catalogs: Record<Lang, Record<string, string>> = { ko, en };

/** Active resolved locale. Components reading `t()` re-render when this changes. */
export const locale = signal<Lang>('ko');

export function resolveLang(pref: LanguagePref): Lang {
  if (pref === 'ko' || pref === 'en') return pref;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ko') ? 'ko' : 'en';
}

export function setLocale(pref: LanguagePref): void {
  locale.value = resolveLang(pref);
}

/** Translate. `{0}`, `{1}`… are replaced by `params`. */
export function t(key: string, params?: (string | number)[]): string {
  const lang = locale.value;
  let s = catalogs[lang][key] ?? catalogs.ko[key] ?? key;
  if (params) {
    params.forEach((p, i) => {
      s = s.split(`{${i}}`).join(String(p));
    });
  }
  return s;
}
